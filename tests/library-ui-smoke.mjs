import { chromium } from '@playwright/test';
import { createServer } from 'vite';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const server = await createServer({ server: { host: '127.0.0.1', port: 0, strictPort: false }, logLevel: 'error' });
await server.listen();
const url = `http://127.0.0.1:${server.httpServer.address().port}`;
const browser = await chromium.launch({ executablePath: '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', headless: true });
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, acceptDownloads: true });
const page = await context.newPage(); const errors = [], results = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('**/api/health', route => route.fulfill({ json: { ok: true, hasApiKey: false } }));
await page.route('**/api/jobs', route => route.fulfill({ json: { jobs: [] } }));
await page.route('**/api/jobs/archive', route => route.fulfill({ json: { format: 'paperlens-jobs', version: 1, exportedAt: Date.now(), records: [] } }));
try {
  await page.goto(url); await page.waitForSelector('.pdf-page-wrap canvas');
  await page.locator('input[type=file]').first().setInputFiles('public/demo.pdf');
  await page.waitForSelector('.analysis-empty');
  await page.getByTitle('文献库管理', { exact: true }).click();
  await page.getByTitle(/编辑 .* 的资料/).first().click();
  await page.getByLabel('文献标题', { exact: true }).fill('文献库功能测试');
  await page.getByLabel('文献作者', { exact: true }).fill('Li; Wang');
  await page.getByLabel('文献期刊', { exact: true }).fill('Nature Medicine');
  await page.getByLabel('发表年份', { exact: true }).fill('2026');
  await page.getByLabel('文献 DOI', { exact: true }).fill('https://doi.org/10.1234/LIBRARY');
  await page.getByLabel('文献标签', { exact: true }).fill('单细胞，关节炎');
  await page.getByRole('button', { name: '保存资料', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '文献资料已保存' }).waitFor();
  assert.match(await page.locator('.lm-table').innerText(), /10.1234\/library/);
  await page.getByTitle('关闭文献资料').click();
  await page.getByLabel('搜索文献库').fill('Li; Wang'); assert.equal(await page.locator('.lm-table tbody tr').count(), 1);
  await page.getByLabel('搜索文献库').fill('no-match-zzzz'); assert.equal(await page.locator('.lm-table tbody tr').count(), 0);
  await page.getByLabel('搜索文献库').fill('');
  const fullText = await page.evaluate(async () => { const storage = await import('/src/lib/storage.ts'); return (await storage.listPapers())[0].pages.find(text => text.trim().length > 30).trim().slice(0, 35); });
  await page.getByLabel('搜索文献库').fill(fullText); assert.equal(await page.locator('.lm-table tbody tr').count(), 1); await page.getByLabel('搜索文献库').fill('');
  results.push('Metadata normalization, author/tag search and PDF full text search');
  await page.getByLabel('选择当前结果全部文献').check();
  await page.getByLabel('批量移动分区').selectOption('ageing');
  await page.getByLabel('批量标签').fill('重点阅读'); await page.getByTitle('应用标签').click();
  assert.match(await page.locator('.lm-table').innerText(), /重点阅读/);
  await page.getByLabel('文献库功能测试的阅读状态', { exact: true }).selectOption('done');
  await page.getByLabel('筛选阅读状态').selectOption('done'); assert.equal(await page.locator('.lm-table tbody tr').count(), 1);
  results.push('Bulk folder/tag changes and reading status filter');
  const alignment = await page.locator('.lm-table').evaluate(table => [...table.querySelectorAll('thead th')].map((cell, i) => Math.abs(cell.getBoundingClientRect().left - table.querySelectorAll('tbody tr:first-child td')[i].getBoundingClientRect().left)));
  assert(alignment.every(delta => delta < 1), 'Library table headings must align with their content columns');
  await page.screenshot({ path: 'artifacts/library-manager-v2.png' });
  await page.getByTitle('关闭文献库管理').click();
  await page.getByTitle('完整备份与恢复').click();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载完整备份', exact: true }).click();
  const download = await downloadPromise; const backupBytes = await readFile(await download.path());
  assert(download.suggestedFilename().endsWith('.paperlens.gz'));
  await page.getByLabel('选择 PaperRead 备份文件').setInputFiles({ name: download.suggestedFilename(), mimeType: 'application/gzip', buffer: backupBytes });
  await page.waitForSelector('.backup-preview');
  assert.match(await page.locator('.backup-preview').innerText(), /已有 1 篇相同编号/);
  await page.screenshot({ path: 'artifacts/backup-manager-v2.png' });
  await page.getByLabel('恢复前，先下载当前文献库的完整备份').uncheck();
  await page.getByRole('button', { name: '合并恢复', exact: true }).click();
  await page.waitForSelector('.backup-success');
  assert.match(await page.locator('.backup-success').innerText(), /保留 1 篇本机已有记录/);
  results.push('Full archive download, import preview and default non-overwriting merge');
  await page.getByTitle('关闭备份与恢复').click(); await page.reload();
  await page.getByTitle('文献库管理', { exact: true }).click(); await page.waitForSelector('.lm-table tbody tr');
  assert.match(await page.locator('.lm-table').innerText(), /重点阅读/); assert.match(await page.locator('.lm-table').innerText(), /文献库功能测试/);
  results.push('Library metadata and reading organization survive reload');
  assert.deepEqual(errors, []); console.log(JSON.stringify({ passed: results, errors }, null, 2));
} finally { await browser.close(); await server.close(); }
